/**
 * 做一顆圖示。名字不認得時回 `null`（呼叫端就只畫文字，不要塞一個空方框）。
 * @param {string} name
 * @returns {SVGSVGElement | null}
 */
export function toolIcon(name) {
  const spec = ICONS[name]
  if (!spec) return null
  const svg = document.createElementNS(SVG_NS, 'svg')
  svg.setAttribute('viewBox', spec.box || '0 0 16 16')
  svg.setAttribute('aria-hidden', 'true')
  svg.classList.add('ws-tool-icon')
  if (spec.fill) svg.classList.add('is-filled')
  for (const d of spec.d) {
    const path = document.createElementNS(SVG_NS, 'path')
    path.setAttribute('d', d)
    // 品牌輪廓都是「外框減內孔」的單一路徑，非零填充會把中間的洞塗滿
    if (spec.fill) path.setAttribute('fill-rule', 'evenodd')
    svg.appendChild(path)
  }
  return svg
}

/**
 * 一個終端機工作階段的狀態圖示（**只有圖示，不放文字**）。
 *
 * `running` 會轉圈圈（CSS 的 `.is-spin`），其餘各是一個靜止的標示：
 * 打勾＝跑完而且離開碼 0、叉＝離開碼非 0、空心圓＝還沒跑過任何指令、
 * 方塊＝這個 shell 已經結束了。
 *
 * @param {{ state?: string, exitCode?: number | null }} item
 * @returns {SVGSVGElement | null}
 */
export function terminalStateIcon(item) {
  const name = stateIconName(item)
  const svg = toolIcon(name)
  if (!svg) return null
  // 圖示名字同時當 class：CSS 靠它上色，測試也靠它斷言「畫出來的到底是哪一顆」
  svg.classList.add('ws-status-icon', name)
  if (name === 'state-running') svg.classList.add('is-spin')
  return svg
}

/**
 * 測試用：狀態對到哪一顆圖示。
 * @param {{ state?: string, exitCode?: number | null }} item
 * @returns {string}
 */
export function stateIconName(item) {
  if (item?.state === 'running') return 'state-running'
  if (item?.state === 'idle') {
    if (item.exitCode === null || item.exitCode === undefined) return 'state-idle'
    return item.exitCode === 0 ? 'state-done' : 'state-fail'
  }
  return 'state-exited'
}
